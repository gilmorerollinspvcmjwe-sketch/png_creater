"""Planner Agent - Intent recognition and task planning.

Phase 2: Analyzes user input, extracts actionable plan for the Builder/Modify pipeline.
Replaces the old "keyword-based intent" with structured planning.
"""

from typing import Dict, Any, Optional, List
from pydantic import BaseModel, Field

from .base import BaseAgent, AgentType, AgentResponse
from ..memory.session import Session, SessionState
from ..tools.theme_matcher import ThemeMatcherTool, ThemeMatcherInput, THEME_CATALOG


# ============================================================================
# Plan model
# ============================================================================

class ActionItem(BaseModel):
    """A single action in the plan."""
    tool: str = Field(..., description="Tool to use")
    args: Dict[str, Any] = Field(default_factory=dict, description="Tool arguments")
    description: str = Field(default="", description="What this step does")


class ExecutionPlan(BaseModel):
    """Execution plan generated by Planner Agent."""
    intent: str = Field(
        default="chat",
        description="new_page / modify_page / query / chat"
    )
    theme_id: str = Field(default="sakura", description="Target theme")
    skill_id: Optional[str] = Field(None, description="Target skill (e.g., sakura-style)")
    component_types: List[str] = Field(
        default_factory=list, description="Expected component types"
    )
    actions: List[ActionItem] = Field(
        default_factory=list, description="Ordered action list"
    )
    estimated_steps: int = Field(default=0, description="Estimated number of steps")
    confidence: float = Field(default=0.5, description="Plan confidence 0-1")


